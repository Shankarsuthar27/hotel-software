export function getStatesForCountry(country) {
  if (!country) return INDIAN_STATES;
  const c = country.toLowerCase().trim();
  if (c === 'india') return INDIAN_STATES;
  if (c === 'algeria') return ALGERIA_WILAYAS;
  if (c === 'united states' || c === 'usa' || c === 'us') return US_STATES;
  // Default to Indian states combined with Algerian (for default mock compatibility)
  return [...INDIAN_STATES, ...ALGERIA_WILAYAS];
}

export function getCitiesForState(state) {
  if (!state) return [];
  if (CITIES_BY_STATE[state]) {
    return CITIES_BY_STATE[state];
  }
  // Case-insensitive match
  const foundKey = Object.keys(CITIES_BY_STATE).find(
    (k) => k.toLowerCase() === state.toLowerCase().trim()
  );
  if (foundKey) return CITIES_BY_STATE[foundKey];
  return [];
}

